/* =========================================================
   Прогресс «докирования» шапки.

   Скрипт не анимирует ничего сам и не знает про внешний вид: он только
   переводит позицию скролла в число 0…1 и кладёт его в CSS-переменную
   --dock на элементе <header>. Вся геометрия — ширина, радиус, отступы,
   обводка, подложка — описана в main.css как функции от этой переменной.
   Такое разделение даёт две вещи: во-первых, переключать состояния классом
   не нужно, трансформация непрерывна и симметрична при прокрутке назад;
   во-вторых, поменять вид шапки можно целиком в CSS, не трогая JS.

   Зависимостей в проекте нет (ни package.json, ни сборки), поэтому никакой
   библиотеки анимаций тут не появляется — задача на несколько строк ванили.
   ========================================================= */
(function () {
  var header = document.querySelector('header');
  if (!header) return;

  /* Движение формы — всё-таки движение. При prefers-reduced-motion просто
     не вмешиваемся: --dock остаётся 0, шапка живёт обычной широкой полосой.
     Проверяем один раз на загрузке и подписываемся на смену настройки,
     чтобы не требовать перезагрузки страницы. */
  var mq = window.matchMedia ? window.matchMedia('(prefers-reduced-motion: reduce)') : null;

  /* Путь прокрутки, на котором трансформация проходит от начала до конца.
     140px — примерно высота самой шапки с запасом: панель собирается за
     первое небольшое движение колеса, но не мгновенно, так что переход
     читается как анимация, а не как переключатель. */
  var DIST = 140;

  /* --------- ширина логотипа под полное имя ---------
     В собранной панели «АБ» сменяется на «Анастасия», и плашка должна
     доехать ровно до ширины этой надписи. Ширину нельзя записать в CSS
     константой: она зависит от шрифта, а Onest грузится асинхронно — до его
     загрузки системный шрифт даёт другую метрику.

     Меряем Range по содержимому span, а не сам span: span лежит в узкой
     ячейке грида и его бокс равен ячейке, тогда как Range возвращает
     реальную ширину отрисованного текста (перенос отключён white-space:
     nowrap, поэтому строка одна). 24px — поля по 12px с каждой стороны,
     чтобы имя не упиралось в скруглённый край.

     Если разметка старая и span'а нет — не делаем ничего: в CSS у --logo-w
     значение по умолчанию 28px, логотип остаётся квадратом. */
  function measureLogo() {
    var logo = header.querySelector('.logo');
    if (!logo) return;
    var full = logo.querySelector('.logo-full');
    if (!full || !document.createRange) return;

    var range = document.createRange();
    range.selectNodeContents(full);
    var w = range.getBoundingClientRect().width;
    range.detach && range.detach();

    if (!(w > 0)) return;
    logo.style.setProperty('--logo-w', Math.ceil(w) + 24 + 'px');
  }

  var last = -1;
  var queued = false;

  function apply() {
    queued = false;

    if (mq && mq.matches) {
      if (last !== 0) { last = 0; header.style.removeProperty('--dock'); }
      return;
    }

    var y = window.pageYOffset || document.documentElement.scrollTop || 0;
    var p = y / DIST;
    if (p < 0) p = 0; else if (p > 1) p = 1;

    /* smoothstep вместо линейного прогресса: у краёв диапазона скорость
       изменения близка к нулю, поэтому ни старт от верха страницы, ни
       фиксация в конечной форме не выглядят как резкая остановка. */
    p = p * p * (3 - 2 * p);

    /* Округление до трёх знаков. Чтение y за кадр почти всегда даёт новое
       значение, но на подпиксельных изменениях перерисовывать шапку
       бессмысленно: сравнение с предыдущим отсекает лишние записи в стиль,
       а значит и лишние пересчёты оформления. */
    p = Math.round(p * 1000) / 1000;
    if (p === last) return;
    last = p;

    header.style.setProperty('--dock', p);
  }

  /* Чтение scrollTop внутри обработчика scroll — синхронный запрос к
     раскладке. Поэтому обработчик сам ничего не считает: он лишь ставит
     задачу на следующий кадр, и за один кадр она выполняется один раз,
     сколько бы событий ни пришло. passive:true — чтобы не тормозить
     прокрутку на тач-устройствах. */
  function schedule() {
    if (queued) return;
    queued = true;
    window.requestAnimationFrame(apply);
  }

  window.addEventListener('scroll', schedule, { passive: true });
  /* resize важен: при смене ширины окна меняется медиавыражение и колонка,
     а прогресс нужно пересчитать и применить к новым правилам. */
  window.addEventListener('resize', schedule, { passive: true });

  if (mq) {
    if (mq.addEventListener) mq.addEventListener('change', schedule);
    else if (mq.addListener) mq.addListener(schedule);
  }

  /* Страницу могли открыть уже прокрученной (возврат по истории, переход
     по якорю) — тогда шапка должна сразу быть в нужной форме, без скачка
     после первого движения колеса. */
  measureLogo();
  apply();

  /* Onest подключён через @font-face и приезжает позже первого кадра. Пока
     его нет, текст рисуется подстановочным шрифтом с другой метрикой, и
     замер получился бы неверным. Перемеряем, когда шрифты готовы. Ошибку
     промиса тоже ловим вторым аргументом: если шрифт не загрузился, лучше
     пересчитать по факту, чем остаться со старым числом. */
  if (document.fonts && document.fonts.ready && document.fonts.ready.then) {
    document.fonts.ready.then(measureLogo, measureLogo);
  }

  /* Отладочный доступ — только при ?headerdebug в адресе, в обычной жизни
     страница ничего в window не добавляет. Нужен для проверки: в тестовом
     окружении программная прокрутка не всегда порождает событие scroll и не
     всегда вытесняет кадр rAF, поэтому пересчёт приходится вызывать вручную. */
  if (location.search.indexOf('headerdebug') !== -1) {
    window.__headerDock = { apply: apply, schedule: schedule, header: header, measureLogo: measureLogo };
  }
})();
