/* =========================================================
   Вступление первого экрана: заявление «Из сложного флоу…» появляется
   крупным планом по центру окна и одним непрерывным движением
   уменьшается до своего настоящего места в вёрстке.

   Почему именно так.

   1. Анимируются только transform и opacity. font-size не трогаем
      принципиально: его изменение пересчитывает перенос строк, высота
      абзаца меняется на каждом кадре и весь первый экран дёргается.
      transform рисуется композитором, раскладка при этом неподвижна,
      поэтому фото, имя и чипсы стоят на своих местах буквально — их
      координаты за время анимации не меняются ни на пиксель.

   2. Конечное состояние — transform:none. Это не «значение, похожее на
      вёрстку», а отсутствие трансформации вообще, так что после анимации
      абзац гарантированно выглядит ровно так же, как без скрипта: тот же
      размер, те же переносы, тот же интерлиньяж. Промахнуться мимо
      конечной точки здесь невозможно по построению.

   3. Начальный масштаб считается от реальных размеров окна и реальной
      ширины абзаца, а не задан числом. Ограничения два: по ширине —
      чтобы увеличенный текст не вылез за окно и не породил горизонтальную
      прокрутку, по высоте — чтобы он уместился в первый экран. На широком
      мониторе получается примерно 1.7×, на телефоне абзац и так занимает
      почти всю ширину, поэтому увеличение там заметно меньше, а основную
      амплитуду даёт перемещение. Это сознательный компромисс: увеличить
      сильнее можно только ценой обрезанных по краям букв.

   4. Переносы строк при масштабировании не меняются — scale растягивает
      уже свёрстанный блок.

   5. Буквы проявляются по одной слева направо, но текст при этом с самого
      начала занимает всю свою конечную раскладку: символы разложены по
      инлайновым span, которые уже стоят на местах, и анимируется только их
      прозрачность. Поэтому ни ширина, ни высота абзаца за время набора не
      меняются, переносы строк зафиксированы с первого кадра, а соседние
      блоки не шевелятся. Классический typewriter через подстановку текста
      (textContent += ch) так не умеет: там строка растёт, перенос скачет и
      высота блока прыгает.

      Пробелы остаются обычными текстовыми узлами, в span не заворачиваются.
      Это важно для переноса строк: разрывы ищутся по пробелам, и трогать их
      не нужно. Разбиение идёт по кодовым точкам, суррогатные пары не
      разрезаются.

      После финиша span-ы разбираются обратно в исходный текстовый узел,
      так что в конце в DOM лежит ровно то же, что было в разметке.

   6. Набор, масштаб и перемещение идут одновременно, а не по очереди:
      трансформация стартует в тот же миг, что и первая буква, и
      продолжается ещё примерно полсекунды после последней. Это сознательно
      — иначе получилась бы «сначала печатаем, потом уменьшаем», то есть два
      отдельных эффекта вместо одного движения.

   Однократность. Запуск привязан к загрузке документа: ни scroll, ни
   IntersectionObserver, ни resize здесь не подписаны вообще, так что
   перезапустить анимацию нечему. Внутри ещё два флага: started не даёт
   сработать второй раз, когда DOMContentLoaded и document.fonts.ready
   приходят оба, а done страхует снятие удержания. Если окно изменят
   размер во время движения, пиксельные значения старта останутся
   прежними, но конец всё равно transform:none, то есть результат
   корректный; перезапуска не произойдёт.

   Зависимостей нет: в проекте нет ни сборки, ни библиотек анимации, а
   Web Animations API умеет всё, что здесь нужно, нативно.
   ========================================================= */
(function () {
  'use strict';

  /* Класс удержания висит на <html>. Пока он там, первый экран скрыт
     (одно правило в main.css). Это нужно, чтобы между первой отрисовкой
     и моментом запуска не мелькнул конечный вид текста. Скрытие — самое
     безопасное промежуточное состояние: оно не может ни обрезать текст,
     ни вызвать прокрутку, в отличие от «примерного» начального масштаба,
     заданного заранее в CSS. */
  var HOLD = 'intro-hold';

  /* Основное движение. 2400мс — середина диапазона 2–3с, которого просит
     сценарий с набором: за это время 74 символа успевают проявиться без
     спешки, а масштаб не выглядит торопливым. */
  var DUR = 2400;

  /* Набор. CHAR — длительность проявления одного символа, шаг между
     соседними символами считается от длины фразы: он растягивается на
     TYPE_SHARE от общего времени, чтобы последняя буква дорисовывалась
     почти в конце движения, но не позже него. Для нынешних 63 видимых
     символов выходит около 30мс на знак — примерно 33 знака в секунду,
     то есть набор читается как единый процесс, а не как медленная печать
     длинной фразы. Границы шага страхуют от крайностей, если текст
     когда-нибудь заметно укоротят или удлинят. */
  var CHAR = 220;
  var STEP_MIN = 14;
  var STEP_MAX = 34;
  /* Доля общего времени, к которой набор должен закончиться. Оставшиеся
     12% текст проходит уже целиком набранным — это тот самый мягкий
     «доезд» в конечное положение. */
  var TYPE_SHARE = 0.88;
  /* Кривая подобрана по замерам пройденного пути: 3% за первые 15%
     времени, 64% к середине, 94% к трём четвертям. То есть короткая
     задержка-разгон, основное движение в середине и длинное мягкое
     оседание в конце. Более резкие варианты (например .38,0,.12,1)
     отдавали 82% пути уже к середине — текст успевал приехать и потом
     заметно «доползал». */
  var EASE = 'cubic-bezier(.55,0,.3,1)';
  var FADE = 'cubic-bezier(.33,0,.08,1)';

  /* Шрифт влияет на перенос строк, значит и на измеряемую высоту абзаца,
     от которой считается начальный масштаб. Поэтому ждём document.fonts,
     но не бесконечно: держать первый экран скрытым дольше примерно трети
     секунды хуже, чем посчитать масштаб по системному шрифту. */
  var FONT_WAIT = 350;

  var root = document.documentElement;

  /* prefers-reduced-motion: ничего не добавляем и не скрываем — страница
     работает так, как будто этого файла нет. */
  var mq = window.matchMedia ? window.matchMedia('(prefers-reduced-motion: reduce)') : null;
  if (mq && mq.matches) return;

  /* Нет Web Animations API — тоже выходим до скрытия первого экрана. */
  if (!window.Element || !Element.prototype || typeof Element.prototype.animate !== 'function') return;

  root.className += ' ' + HOLD;

  var done = false;
  function release() {
    if (done) return;
    done = true;
    root.className = root.className.replace(new RegExp('(^|\\s)' + HOLD + '(\\s|$)'), ' ');
  }

  /* Страховка. Если дальше что-то пойдёт не так — не загрузится шрифт,
     не найдётся абзац, выбросится исключение, — первый экран обязан
     стать видимым. Три секунды с запасом больше любого штатного пути. */
  setTimeout(release, 3000);

  var started = false;
  function start() {
    if (started) return;
    started = true;
    try { run(); } catch (e) { release(); }
  }

  function run() {
    var hero = document.querySelector('.hero');
    var el = hero ? hero.querySelector('.statement') : null;
    if (!el) { release(); return; }

    /* clientWidth, а не innerWidth: innerWidth включает вертикальную
       полосу прокрутки, и запас по ширине оказался бы завышен ровно на
       её толщину — то есть появилась бы горизонтальная прокрутка. */
    var vw = root.clientWidth || window.innerWidth;
    var vh = window.innerHeight || root.clientHeight;

    /* Измеряем конечную геометрию. Класс удержания задаёт только
       прозрачность, раскладку он не меняет, поэтому снимать его для
       измерения не нужно — rect уже настоящий. */
    var r = el.getBoundingClientRect();
    if (!r.width || !r.height) { release(); return; }

    var side = Math.max(16, vw * 0.03);
    var s = Math.min((vw - side * 2) / r.width, (vh * 0.78) / r.height, 2.6);
    if (!(s > 1)) s = 1;
    s = Math.round(s * 1000) / 1000;

    /* Вертикаль: центр увеличенного абзаца ставим в верхнюю часть окна,
       на 42% высоты. Отсюда же берётся и «перемещение» — к концу
       анимации смещение обнуляется, и текст приезжает в своё место в
       колонке. Значение отрицательное (абзац лежит ниже этой точки), так
       что документ не удлиняется и лишней прокрутки не возникает.

       Почему 42, а не ровно середина. На телефоне абзац и так занимает
       почти всю ширину колонки, увеличивать его там практически некуда
       (см. выше, масштаб выходит около 1.02), и вся выразительность
       движения держится на перемещении. Сдвиг точки старта выше середины
       удлиняет путь: на 375×812 это 137px вместо 56px, то есть движение
       становится отчётливо заметным. На широком экране разница тоже в
       плюс и ничему не мешает. */
    var ty = Math.round(vh * 0.42 - (r.top + r.height / 2));

    /* Страховка от залезания под шапку: если при таком смещении верх
       увеличенного абзаца оказывается выше кромки окна, опускаем старт
       ровно настолько, чтобы текст целиком остался на виду. Проверка
       нужна для коротких окон, где масштаб ограничен высотой. */
    var topAt = r.top + r.height / 2 + ty - (r.height * s) / 2;
    if (topAt < 12) ty += 12 - topAt;
    ty = Math.round(ty);

    var from = 'translate3d(0,' + ty + 'px,0) scale(' + s + ')';

    el.style.willChange = 'transform, opacity';

    /* Масштаб и смещение — одна анимация одного свойства, поэтому они
       физически не могут разъехаться во времени: это буквально одно
       движение, а не два совпадающих. */
    var move = el.animate(
      [{ transform: from }, { transform: 'none' }],
      { duration: DUR, easing: EASE, fill: 'both' }
    );

    /* Набор. split раскладывает текст по span-ам, не меняя раскладку;
       если абзац устроен сложнее, чем один текстовый узел (например в
       нём есть вложенная разметка), split вернёт null и мы честно
       откатимся на прежнее проявление абзаца целиком. */
    var piece = split(el);
    var show = [];

    if (piece) {
      /* Шаг считается из длины текста, а не задан числом: набор ровно
         укладывается в отведённую долю времени независимо от того,
         сколько в фразе символов. Для 63 знаков это ~30.5мс, последняя
         буква дорисовывается на 2111мс из 2400. */
      var n = piece.chars.length;
      var step = n > 1 ? (DUR * TYPE_SHARE - CHAR) / (n - 1) : 0;
      if (step < STEP_MIN) step = STEP_MIN;
      if (step > STEP_MAX) step = STEP_MAX;

      for (var c = 0; c < n; c++) {
        show.push(piece.chars[c].animate(
          [{ opacity: 0 }, { opacity: 1 }],
          { duration: CHAR, delay: Math.round(c * step), easing: FADE, fill: 'both' }
        ));
      }
    } else {
      show.push(el.animate(
        [{ opacity: 0 }, { opacity: 1 }],
        { duration: 420, easing: FADE, fill: 'both' }
      ));
    }

    /* Остальные элементы первого экрана проявляются к концу движения.
       Они не двигаются — только прозрачность, координаты неизменны.
       Без этого крупный текст в начале наезжал бы на фото и имя: при
       масштабе около 1.7 абзац перекрывает соседние блоки, и кадр
       читался бы как ошибка вёрстки, а не как вступление. */
    var rest = [];
    var kids = hero.children;
    for (var i = 0; i < kids.length; i++) {
      if (kids[i] === el) continue;
      rest.push(kids[i].animate(
        [{ opacity: 0 }, { opacity: 1 }],
        { duration: 620, delay: Math.round(DUR * 0.45), easing: FADE, fill: 'both' }
      ));
    }

    /* Удержание снимаем здесь, а не раньше: к этой строке все анимации
       уже созданы с fill:'both', то есть начальные значения применены.
       Первый же нарисованный кадр — честное начальное состояние. */
    release();

    move.addEventListener('finish', function () {
      /* fill:'both' после финиша продолжает навязывать конечные значения.
         Они совпадают с естественными (transform:none, opacity:1), но
         оставлять висящие анимации на элементе незачем: отменяем их и
         убираем will-change, чтобы абзац вернулся к обычной жизни —
         выделяемый, копируемый, без следов трансформации в стилях. */
      el.style.removeProperty('will-change');
      move.cancel();
      for (var k = 0; k < show.length; k++) show[k].cancel();
      for (var j = 0; j < rest.length; j++) rest[j].cancel();

      /* Разбираем span-ы обратно. После этой строки в разметке лежит тот
         же единственный текстовый узел, что и был, — никаких следов
         анимации в DOM, ничего лишнего в дереве доступности, текст
         выделяется и копируется как обычный. */
      if (piece) piece.restore();
    });
  }

  /* Раскладка текста по символам.
     Возвращает null, если внутри не один текстовый узел: лезть в чужую
     разметку и пересобирать её вслепую — верный способ что-нибудь
     сломать, лучше отказаться от набора и оставить обычное проявление.

     Пробельные символы остаются обычным текстом между span-ами: именно по
     ним браузер ищет места переноса строк, и заворачивать их в элементы
     незачем. Видимые символы идут по кодовым точкам, чтобы не разрезать
     суррогатную пару пополам. */
  function split(el) {
    var node = el.firstChild;
    if (!node || node !== el.lastChild || node.nodeType !== 3) return null;

    var raw = node.data;
    var frag = document.createDocumentFragment();
    var chars = [];
    var gap = '';
    var i = 0;

    while (i < raw.length) {
      var code = raw.charCodeAt(i);
      var len = (code >= 0xD800 && code <= 0xDBFF && i + 1 < raw.length) ? 2 : 1;
      var ch = raw.substr(i, len);
      i += len;

      if (/\s/.test(ch)) { gap += ch; continue; }
      if (gap) { frag.appendChild(document.createTextNode(gap)); gap = ''; }

      var span = document.createElement('span');
      span.textContent = ch;
      /* Стартовое значение в инлайне: анимации создаются чуть позже, и
         без него между вставкой и первым кадром мог бы мелькнуть готовый
         текст. Удержание первого экрана это и так закрывает, но лишняя
         страховка здесь ничего не стоит. */
      span.style.opacity = '0';
      frag.appendChild(span);
      chars.push(span);
    }
    if (gap) frag.appendChild(document.createTextNode(gap));
    if (!chars.length) return null;

    el.textContent = '';
    el.appendChild(frag);

    return {
      chars: chars,
      restore: function () {
        el.textContent = raw;
      }
    };
  }

  function schedule() {
    var fonts = document.fonts;
    if (fonts && fonts.status === 'loaded') { start(); return; }
    if (fonts && fonts.ready && typeof fonts.ready.then === 'function') {
      fonts.ready.then(start, start);
      setTimeout(start, FONT_WAIT);
      return;
    }
    start();
  }

  /* Скрипт подключён в <head> без defer — именно поэтому класс удержания
     ставится до первой отрисовки. Сам запуск, разумеется, ждёт разметку. */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', schedule);
  } else {
    schedule();
  }

  /* Отладочный доступ — только при ?herodebug в адресе. В тестовом
     окружении нужен синхронный запуск с известного момента; в обычной
     жизни страница ничего в window не добавляет. */
  if (location.search.indexOf('herodebug') !== -1) {
    window.__heroIntro = {
      start: start,
      release: release,
      state: function () { return { started: started, done: done }; }
    };
  }
})();
